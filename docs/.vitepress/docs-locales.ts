export function getLocalizedDocs(lang: string): (typeof localizedDocs)[keyof typeof localizedDocs] | undefined {
  return localizedDocs[lang as keyof typeof localizedDocs]
}

export function getUnprefixedDocsPath(path: string): string {
  const slash = path.indexOf('/')
  if (slash === -1) return path
  const prefix = path.slice(0, slash)
  return prefix === 'zh' || getLocalizedDocs(prefix) ? path.slice(slash + 1) : path
}
